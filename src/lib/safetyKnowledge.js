/**
 * วิเคราะห์ขั้นตอนงาน (step) แล้วคืนค่าอันตราย+มาตรการป้องกันที่แนะนำ
 * จับคู่จากคำสำคัญที่พบในข้อความ รวมผลจากทุกหมวดที่ตรงกัน (ไม่ซ้ำ)
 * ถ้าไม่พบคำสำคัญตรงเลย จะใช้หมวด "งานทั่วไป" เป็นค่าเริ่มต้น
 */
export function analyzeSafety(stepText) {
  const text = (stepText || "").toLowerCase();
  if (!text.trim()) return { hazards: [], controls: [], matchedCategories: [] };

  const matched = SAFETY_KNOWLEDGE.filter(
    (k) => k.keywords.length > 0 && k.keywords.some((kw) => text.includes(kw.toLowerCase()))
  );

  const source = matched.length > 0 ? matched : [SAFETY_KNOWLEDGE.find((k) => k.category === "งานทั่วไป (ค่าเริ่มต้น)")];

  const hazards = [...new Set(source.flatMap((k) => k.hazards))];
  const controls = [...new Set(source.flatMap((k) => k.controls))];
  const matchedCategories = source.map((k) => k.category);

  return { hazards, controls, matchedCategories };
}
